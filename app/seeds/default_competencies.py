def seed_default_competencies(conn, company_id):
    """Создаёт дефолтные компетенции и вопросы для компании.

    conn — открытое psycopg-подключение; коммит выполняется внутри.
    """
    with conn.cursor() as cur:
        for comp_order, comp in enumerate(DEFAULT_COMPETENCIES):
            cur.execute(
                """
                INSERT INTO competencies (company_id, name, description, sort_order, active)
                VALUES (%s, %s, %s, %s, true)
                RETURNING id
                """,
                (company_id, comp["name"], comp["description"], comp_order),
            )
            competency_id = cur.fetchone()["id"]
            for q_order, (text, qtype) in enumerate(comp["questions"]):
                cur.execute(
                    """
                    INSERT INTO questions (competency_id, text, qtype, sort_order)
                    VALUES (%s, %s, %s, %s)
                    """,
                    (competency_id, text, qtype, q_order),
                )
    conn.commit()
